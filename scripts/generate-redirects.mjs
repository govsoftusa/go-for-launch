#!/usr/bin/env node
/**
 * Builds `public/_redirects` from the extracted dataset.
 *
 * Cloudflare applies static redirects at the edge before the Worker runs, so
 * every legacy URL is answered without a database read. The file has a hard
 * limit of 2,100 rules, which this corpus exceeds: 2,477 rules came out of the
 * legacy 404-redirect plugin alone. Rules are therefore prioritised, and
 * whatever does not fit is emitted to `src/lib/overflow-redirects.json` for the
 * Worker to resolve as a fallback. Nothing is silently dropped.
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const CLOUDFLARE_STATIC_LIMIT = 2100;

const datasetDir = process.argv[2] ?? '../dataset';
const projectDir = path.resolve(process.argv[3] ?? '.');

const redirects = JSON.parse(
  fs.readFileSync(path.resolve(datasetDir, 'redirects.json'), 'utf8'),
);

const site = JSON.parse(fs.readFileSync(path.resolve(datasetDir, 'site.json'), 'utf8'));
const canonicalHost = new URL(site.homeUrl).host;
const config = {
  canonicalHost,
  apexHost: canonicalHost.replace(/^www\./, ''),
};

/**
 * Structural rules first: they cover whole families of URLs and cost one line
 * each. Shortlinks last: `/?p=123` is a query-string form few crawlers still
 * hold, and there are one per post.
 */
const priority = { structural: 0, wbz404: 1, shortlink: 3 };
const rank = (rule) => priority[rule.source] ?? 2;

/**
 * Rules already expressed in the handwritten header, so the generated body
 * must not repeat them.
 */
const HEADER_RULES = new Set([
  '/feed/',
  '/feed',
  '/comments/feed/',
  '/wp-login.php',
  '/xmlrpc.php',
]);

/**
 * The legacy 404-redirect plugin recorded every URL that ever 404'd, including
 * vulnerability probes, and an earlier administrator pointed a large number of
 * them at the home page. Carrying those forward would spend a scarce edge
 * redirect budget teaching attackers that their probes get a 301, and would
 * dilute the home page's inbound link profile. A 404 is the correct answer.
 */
function isJunk(rule) {
  const { from, to } = rule;
  if (/^\/(homepage|home|blog)\/?$/.test(to) && from.includes('?')) return true;
  if (/\b(cmd|exec|eval|base64|passwd|shell|union\s+select)\b/i.test(from)) return true;
  if (/\.(php|asp|aspx|jsp|cgi|env|git|sql|bak)\b/i.test(from)) return true;
  if (/[<>'"\\]/.test(from)) return true;
  if (from.startsWith('/wp-')) return true;
  return false;
}

const seen = new Set();
const deduped = [];
const dropped = [];
for (const rule of redirects) {
  const from = rule.from.startsWith('/') ? rule.from : `/${rule.from}`;
  if (seen.has(from)) continue;
  if (from === rule.to) continue;
  if (HEADER_RULES.has(from)) continue;
  seen.add(from);
  const candidate = { ...rule, from };
  if (isJunk(candidate)) {
    dropped.push(candidate);
    continue;
  }
  deduped.push(candidate);
}

/**
 * The three duplicate home pages WordPress accumulated. They are real routes
 * with inbound links, so they redirect rather than 404, but they collapse onto
 * the canonical root.
 */
for (const duplicate of ['/home/', '/homepage/', '/blog/']) {
  if (seen.has(duplicate)) continue;
  seen.add(duplicate);
  deduped.push({ from: duplicate, to: '/', status: 301, source: 'structural' });
}

deduped.sort((a, b) => rank(a) - rank(b) || a.from.localeCompare(b.from));

const kept = deduped.slice(0, CLOUDFLARE_STATIC_LIMIT);
const overflow = deduped.slice(CLOUDFLARE_STATIC_LIMIT);

const header = [
  '# Generated by scripts/generate-redirects.mjs. Do not edit by hand.',
  '# Legacy WordPress URLs, preserved so eight years of inbound links and',
  '# search results keep resolving.',
  '',
  '# Canonical host.',
  `https://${config.apexHost}/* https://${config.canonicalHost}/:splat 301`,
  '',
  '# Feeds.',
  '/feed/ /rss.xml 301',
  '/feed /rss.xml 301',
  '/comments/feed/ /rss.xml 301',
  '',
  '# WordPress search.',
  '/?s=:term /search/?q=:term 301',
  '',
  '# Endpoints that no longer exist. 410 tells a crawler to stop asking,',
  '# where a 404 invites it to retry indefinitely.',
  '/wp-login.php /404/ 410',
  '/xmlrpc.php /404/ 410',
  '/wp-admin/* /404/ 410',
  '/wp-json/* /404/ 410',
  '',
].join('\n');

const lines = kept.map((rule) => `${rule.from} ${rule.to} ${rule.status}`);

fs.mkdirSync(path.join(projectDir, 'public'), { recursive: true });
fs.writeFileSync(
  path.join(projectDir, 'public', '_redirects'),
  `${header}${lines.join('\n')}\n`,
);

fs.mkdirSync(path.join(projectDir, 'src', 'lib'), { recursive: true });
fs.writeFileSync(
  path.join(projectDir, 'src', 'lib', 'overflow-redirects.json'),
  `${JSON.stringify(
    Object.fromEntries(overflow.map((rule) => [rule.from, { to: rule.to, status: rule.status }])),
    null,
    2,
  )}\n`,
);

console.log(
  `Wrote public/_redirects with ${lines.length} edge rules and ` +
    `src/lib/overflow-redirects.json with ${overflow.length} Worker-resolved rules.`,
);
if (overflow.length) {
  console.log(
    `Note: ${overflow.length} rules exceed the Cloudflare static redirect limit of ` +
      `${CLOUDFLARE_STATIC_LIMIT} and are handled in the Worker instead.`,
  );
}

fs.writeFileSync(
  path.join(projectDir, 'src', 'lib', 'dropped-redirects.json'),
  `${JSON.stringify(
    {
      note:
        'Legacy rules deliberately not carried forward: vulnerability probes and junk ' +
        'query strings an earlier administrator pointed at the home page. These now 404.',
      count: dropped.length,
      rules: dropped.map((rule) => rule.from),
    },
    null,
    2,
  )}\n`,
);
console.log(`Dropped ${dropped.length} junk legacy rules (recorded in dropped-redirects.json).`);
